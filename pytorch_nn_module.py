"""Using Sequential:"""

# use sequential to create network
# sequential automatically performs forword opertions when called

import torch
import torch.nn as nn

class Model(nn.Module):

  def __init__(self,num_features):
    super().__init__()

    # define network
    self.network = nn.Sequential(
        nn.Linear(num_features,3),
        nn.ReLU(),
        nn.Linear(3,1),
        nn.Sigmoid()
    )

  def forward(self,features):
    # call forword
    out = self.network(features)
    return out

features = torch.rand(10,5) # define features
model = Model(features.shape[1]) # create model
outputs=model(features) # get outputs
print(outputs)

