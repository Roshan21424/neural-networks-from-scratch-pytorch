import torch
import torch.nn as nn

# must inherit nn.Module as it is the base class which has all the implementation
class Model(nn.Module):

  # must call parents constructor
  def __init__(self,num_features):
    super().__init__()

    # define forward
    self.linear = nn.Linear(num_features,1) # single neuron
    self.sigmoid = nn.Sigmoid() # activation function

  def forward(self,features):

    # perform forward
    out = self.linear(features)
    out = self.sigmoid(out)
    return out

# define features
features = torch.rand(10,5)

# create model
model = Model(features.shape[1])

# call forward
# outputs =model.forward(features) # non standard method
outputs=model(features) # standard method, automatically calls forward method(done by __call__ magic method)
print(outputs)

# inspect parameters
model.linear.weight
model.linear.bias

